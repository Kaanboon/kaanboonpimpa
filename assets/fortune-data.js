const bangkokCalendar = new Intl.DateTimeFormat('en-GB', {
  timeZone: 'Asia/Bangkok',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});

export function bangkokDay(date) {
  const parts = bangkokCalendar.formatToParts(date);
  const number = (type) => Number(parts.find((part) => part.type === type).value);
  return Date.UTC(number('year'), number('month') - 1, number('day')) / 86400000;
}

export function readingFor(day, birthDay) {
  return dailyReadings.map(({ label, step, offset, lines }) => {
    const position = (day * step + birthDay * offset) % lines.length;
    return { label, text: lines[(position + lines.length) % lines.length] };
  });
}
